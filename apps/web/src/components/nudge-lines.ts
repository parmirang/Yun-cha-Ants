import { WORK_HOURS_PER_DAY, type Mood } from "@yca/shared";

/**
 * 화면 맨 아래에서 등을 떠미는 한마디.
 *
 * 상단 카운터(`countdown-lines.ts`)·개미 말풍선(`speech-lines.ts`)과 **같은 시간 축**을
 * 쓴다 — 경계는 여기 `nudgeTier` 한 곳에 두고 셋이 함께 가져다 쓴다. 같은 -5%라도
 * 100만원어치면 20분이고 1억어치면 사흘이라, 그때 들어야 할 말이 다르다.
 *
 * 셋이 같은 축이어도 겹치지 않는 건 **역할도 소재도 갈라놨기 때문**이다.
 *   상단   "{시간} 만큼 __"을 끝맺는 서술어 — 노동 동사구만
 *   말풍선 개미의 1인칭 혼잣말 — 몸 상태와 개미 살림(굴·먹이·여왕개미)
 *   하단   제3자 시선의 배경 문장 — 생활 소재(커피·점심·휴가·월급·사표)와 훈수
 * 소재가 겹치면 세 줄이 동시에 같은 얘기를 한다. `pnpm --filter @yca/web lines`가
 * 같은 구간에서 문장이 겹치지 않는지 검사한다.
 *
 * 개미의 껍질 색·배경 날씨만 수익률 레벨(`sceneLevelFromStage`)을 따른다.
 *
 * 이 문구들은 본문 폰트로 그린다 (픽셀 폰트 서브셋 대상이 아니다) — 그래서
 * `speech-lines.ts`와 한 파일에 두지 않았다. 여기 문구를 고쳐도 폰트는 다시
 * 굽지 않아도 된다.
 */

const HOUR = 3600;
/** 1근무일 = 8시간. 카운터 표기(`formatWorkSpanWords`)가 "출근 N번"으로 넘어가는 지점이다. */
const WORK_DAY = WORK_HOURS_PER_DAY * HOUR;

/**
 * 시간 구간. **노동의 단위로 끊는다** — 10분 · 한 시간 · 하루 · 한 주 · 한 달 · 반년.
 *
 * 예전엔 `1시간 / 8시간 / 24시간 / 닷새` 넷이었는데 맨 위 구간에 상한이 없어서
 * 닷새치와 반년치가 같은 풀을 썼다 — 3주치 손익에도 "평생 안 나가도 돼"가 떴다.
 * 위아래로 하나씩 늘려 일곱으로 폈다.
 */
const TIER_BOUNDS = [
  10 * 60, // 10분 — 티끌
  HOUR, // 한 시간
  WORK_DAY, // 하루치 노동 (여기부터 "출근 N번" 표기)
  5 * WORK_DAY, // 한 주치
  20 * WORK_DAY, // 한 달치 (봉 길이가 멈추는 지점과 같은 자)
  120 * WORK_DAY, // 반년치
] as const;

export const TIER_COUNT = TIER_BOUNDS.length + 1;

/**
 * 이 구간부터 시간이 "출근 N번"으로 적힌다.
 *
 * 상단 문구가 "나가다 / 결근 / 도장" 은유를 여기서부터만 쓰는 근거다 —
 * 그 아래에서는 "23분 만큼 안 나가도 돼"가 되어 뜻이 안 선다.
 */
export const WORK_UNIT_TIER = 3;

export function nudgeTier(seconds: number): number {
  const safe = Math.max(0, seconds);
  const index = TIER_BOUNDS.findIndex((bound) => safe < bound);

  return index === -1 ? TIER_BOUNDS.length : index;
}

